import type { Delivery, DockEntry, PerformanceData, AlertItem } from '../types';

function makeSteps(status: Delivery['status']) {
  const all = [
    { key: 'arrival' as const, label: 'Arrivée' },
    { key: 'dock' as const, label: 'Quai' },
    { key: 'loadingStart' as const, label: 'Début charg.' },
    { key: 'loadingEnd' as const, label: 'Fin charg.' },
    { key: 'departure' as const, label: 'Départ' },
  ];

  const times: Record<string, string[]> = {
    WAITING: ['', '', '', '', ''],
    AT_DOCK: ['20:14', '20:31', '', '', ''],
    LOADING: ['19:45', '20:02', '20:18', '', ''],
    LOADED: ['18:30', '18:47', '19:00', '21:12', ''],
    DEPARTED: ['17:10', '17:28', '17:45', '19:50', '20:15'],
    ALERT: ['20:05', '', '', '', ''],
  };

  const doneCounts: Record<string, number> = {
    WAITING: 0,
    AT_DOCK: 2,
    LOADING: 3,
    LOADED: 4,
    DEPARTED: 5,
    ALERT: 1,
  };

  const doneCount = doneCounts[status] ?? 0;
  const ts = times[status] ?? times['WAITING'];

  return all.map((s, i) => ({
    ...s,
    time: ts[i] || undefined,
    done: i < doneCount,
    active: i === doneCount && status !== 'DEPARTED' && status !== 'WAITING',
  }));
}

